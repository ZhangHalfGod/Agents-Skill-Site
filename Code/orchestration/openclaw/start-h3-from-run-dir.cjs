#!/usr/bin/env node
/**
 * start-h3-from-run-dir.cjs — 确定性启动 H3（不依赖 main LLM 回合成功）
 *
 *   node start-h3-from-run-dir.cjs --run-dir <run-dir> [--detach] [--force]
 *
 * Windows detach：写 h3-detach-launcher.ps1（自带日志）+ Start-Process -WindowStyle Hidden
 * （不用 RedirectStandardOutput——在部分环境会瞬间退出且无日志）
 * 日志：h3-wrapper-detach.out.log / .err.log / h3-detach.pid
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ORCH = path.resolve(__dirname);
const CHECK = path.join(ORCH, 'check-h3-done.cjs');
const COOLDOWN_MS = 2 * 60 * 1000;
const DEAD_RETRY_MS = 30 * 1000;

function parseArgs(argv) {
  const out = { runDir: '', detach: true, force: false };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--run-dir') out.runDir = path.resolve(argv[++i] || '');
    else if (argv[i] === '--no-detach') out.detach = false;
    else if (argv[i] === '--detach') out.detach = true;
    else if (argv[i] === '--force') out.force = true;
  }
  return out;
}

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return null;
  }
}

function writeJson(p, obj) {
  fs.writeFileSync(p, JSON.stringify(obj, null, 2) + '\n', 'utf8');
}

function isPidAlive(pid) {
  const n = Number(pid);
  if (!n || n <= 0) return false;
  try {
    process.kill(n, 0);
    return true;
  } catch {
    return false;
  }
}

function runCheck(runDir, repoRoot) {
  const r = spawnSync(process.execPath, [CHECK, '--run-dir', runDir, '--work-dir', repoRoot, '--expect-commit'], {
    encoding: 'utf8',
  });
  try {
    return JSON.parse((r.stdout || '').trim());
  } catch {
    return { done: false, reason: 'parse_error' };
  }
}

function inferRepoRoot(runDir) {
  const watch = readJson(path.join(runDir, 'h3-watch.json'));
  if (watch?.repoRoot) return watch.repoRoot;
  if (watch?.workDir) return watch.workDir;
  const wrapper = path.join(runDir, 'h3-run-wrapper.ps1');
  if (fs.existsSync(wrapper)) {
    const t = fs.readFileSync(wrapper, 'utf8');
    const m = t.match(/\$repoRoot\s*=\s*['"]([^'"]+)['"]/);
    if (m) return path.resolve(m[1]);
    const w = t.match(/\$workDir\s*=\s*['"]([^'"]+)['"]/);
    if (w) return path.resolve(w[1]);
  }
  return runDir;
}

function psQuote(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function writeDetachLauncher(runDir, wrapperPath, outLog, errLog, pidFile) {
  const launcherPath = path.join(runDir, 'h3-detach-launcher.ps1');
  const body = [
    '# auto-generated by start-h3-from-run-dir.cjs — do not edit',
    '$ErrorActionPreference = "Continue"',
    `$wrapper = ${psQuote(wrapperPath)}`,
    `$outLog = ${psQuote(outLog)}`,
    `$errLog = ${psQuote(errLog)}`,
    `$pidFile = ${psQuote(pidFile)}`,
    `$runDir = ${psQuote(runDir)}`,
    'Set-Location -LiteralPath $runDir',
    '"$PID" | Set-Content -Encoding ASCII $pidFile',
    '("LAUNCH pid={0} at={1}" -f $PID, (Get-Date).ToString("o")) | Set-Content -Encoding UTF8 $outLog',
    '"" | Set-Content -Encoding UTF8 $errLog',
    'try {',
    '  & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $wrapper 1>> $outLog 2>> $errLog',
    '  $code = $LASTEXITCODE',
    '} catch {',
    '  $_ | Out-File -Append -FilePath $errLog -Encoding UTF8',
    '  $code = 1',
    '}',
    '("EXIT code={0} at={1}" -f $code, (Get-Date).ToString("o")) | Out-File -Append -FilePath $outLog -Encoding UTF8',
    'exit $code',
    '',
  ].join('\r\n');
  fs.writeFileSync(launcherPath, body, 'utf8');
  return launcherPath;
}

/**
 * Windows：Start-Process 无 Redirect（避免瞬间退出）；launcher 自写日志与 pid 文件。
 */
function startDetachedWindows(wrapperPath, runDir) {
  const outLog = path.join(runDir, 'h3-wrapper-detach.out.log');
  const errLog = path.join(runDir, 'h3-wrapper-detach.err.log');
  const pidFile = path.join(runDir, 'h3-detach.pid');
  try {
    if (fs.existsSync(pidFile)) fs.unlinkSync(pidFile);
  } catch {
    /* ignore */
  }

  const launcherPath = writeDetachLauncher(runDir, wrapperPath, outLog, errLog, pidFile);

  const ps = [
    '$ErrorActionPreference = "Stop"',
    `$p = Start-Process -FilePath "powershell.exe" -ArgumentList @("-NoProfile","-ExecutionPolicy","Bypass","-File",${psQuote(launcherPath)}) -WorkingDirectory ${psQuote(runDir)} -WindowStyle Hidden -PassThru`,
    'if (-not $p) { Write-Error "Start-Process returned null"; exit 1 }',
    'Write-Output $p.Id',
  ].join('; ');

  const r = spawnSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', ps], {
    encoding: 'utf8',
    windowsHide: true,
  });

  const startPid = Number((r.stdout || '').trim().split(/\r?\n/).filter(Boolean).pop());
  if (r.status !== 0 || !startPid) {
    return {
      ok: false,
      pid: null,
      outLog,
      errLog,
      error: (r.stderr || r.stdout || 'Start-Process failed').trim().slice(0, 2000),
      exitCode: r.status,
    };
  }

  // 等 launcher 写入 pid 文件（最多 3s）
  let launcherPid = startPid;
  const deadline = Date.now() + 3000;
  while (Date.now() < deadline) {
    if (fs.existsSync(pidFile)) {
      const n = Number(String(fs.readFileSync(pidFile, 'utf8')).trim());
      if (n > 0) {
        launcherPid = n;
        break;
      }
    }
    spawnSync('powershell.exe', ['-NoProfile', '-Command', 'Start-Sleep -Milliseconds 100'], {
      windowsHide: true,
    });
  }

  return {
    ok: true,
    pid: launcherPid,
    startProcessPid: startPid,
    outLog,
    errLog,
    pidFile,
    launcherPath,
  };
}

function startDetachedUnix(wrapperPath, runDir) {
  const { spawn } = require('child_process');
  const outLog = path.join(runDir, 'h3-wrapper-detach.out.log');
  const errLog = path.join(runDir, 'h3-wrapper-detach.err.log');
  const outFd = fs.openSync(outLog, 'w');
  const errFd = fs.openSync(errLog, 'w');
  const child = spawn('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', wrapperPath], {
    detached: true,
    stdio: ['ignore', outFd, errFd],
    cwd: runDir,
    windowsHide: true,
  });
  child.unref();
  try {
    fs.closeSync(outFd);
    fs.closeSync(errFd);
  } catch {
    /* ignore */
  }
  return { ok: true, pid: child.pid || null, outLog, errLog };
}

function main() {
  const args = parseArgs(process.argv);
  if (!args.runDir) {
    console.error('usage: node start-h3-from-run-dir.cjs --run-dir <path> [--detach] [--force]');
    process.exit(2);
  }

  const runDir = args.runDir;
  const wrapperPath = path.join(runDir, 'h3-run-wrapper.ps1');
  const goalPath = path.join(runDir, 'h3-goal.md');
  const startPath = path.join(runDir, 'h3-start.json');
  const watchPath = path.join(runDir, 'h3-watch.json');

  if (!fs.existsSync(wrapperPath)) {
    process.stdout.write(JSON.stringify({ ok: false, action: 'skip', reason: 'missing_h3_run_wrapper' }, null, 2) + '\n');
    process.exit(1);
  }
  if (!fs.existsSync(goalPath)) {
    process.stdout.write(JSON.stringify({ ok: false, action: 'skip', reason: 'missing_h3_goal' }, null, 2) + '\n');
    process.exit(1);
  }

  const repoRoot = inferRepoRoot(runDir);
  const check = runCheck(runDir, repoRoot);
  if (check.done) {
    process.stdout.write(JSON.stringify({ ok: true, action: 'skip', reason: 'h3_already_done', check }, null, 2) + '\n');
    process.exit(0);
  }

  const prev = readJson(startPath);
  const now = Date.now();
  if (prev?.wrapperPid && isPidAlive(prev.wrapperPid) && !args.force) {
    process.stdout.write(
      JSON.stringify(
        {
          ok: true,
          action: 'skip',
          reason: 'already_running',
          startedAt: prev.startedAt,
          wrapperPid: prev.wrapperPid,
        },
        null,
        2,
      ) + '\n',
    );
    process.exit(0);
  }

  if (prev?.startedAt && !args.force) {
    const elapsed = now - Date.parse(prev.startedAt);
    const alive = prev.wrapperPid ? isPidAlive(prev.wrapperPid) : false;
    const limit = alive ? COOLDOWN_MS : DEAD_RETRY_MS;
    if (elapsed >= 0 && elapsed < limit) {
      process.stdout.write(
        JSON.stringify(
          {
            ok: true,
            action: 'skip',
            reason: alive ? 'cooldown' : 'dead_cooldown',
            startedAt: prev.startedAt,
            wrapperPid: prev.wrapperPid || null,
            cooldownMs: limit - elapsed,
            alive,
          },
          null,
          2,
        ) + '\n',
      );
      process.exit(0);
    }
  }

  const startedAt = new Date().toISOString();

  if (!args.detach) {
    const r = spawnSync(
      'powershell.exe',
      ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', wrapperPath],
      { encoding: 'utf8', cwd: runDir, stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024 },
    );
    if (r.stdout) process.stdout.write(r.stdout);
    if (r.stderr) process.stderr.write(r.stderr);
    process.stdout.write(
      JSON.stringify(
        {
          ok: r.status === 0,
          action: 'sync',
          startedAt,
          exitCode: r.status,
          check: runCheck(runDir, repoRoot),
        },
        null,
        2,
      ) + '\n',
    );
    process.exit(r.status === 0 ? 0 : 1);
  }

  const launched =
    process.platform === 'win32'
      ? startDetachedWindows(wrapperPath, runDir)
      : startDetachedUnix(wrapperPath, runDir);

  if (!launched.ok) {
    writeJson(startPath, {
      startedAt,
      wrapperPid: null,
      detached: true,
      failed: true,
      error: launched.error,
      wrapperPath,
      repoRoot,
      outLog: launched.outLog,
      errLog: launched.errLog,
    });
    process.stdout.write(
      JSON.stringify(
        {
          ok: false,
          action: 'start_failed',
          startedAt,
          error: launched.error,
          outLog: launched.outLog,
          errLog: launched.errLog,
        },
        null,
        2,
      ) + '\n',
    );
    process.exit(1);
  }

  const wrapperPid = launched.pid;
  const stillAlive = isPidAlive(wrapperPid);
  writeJson(startPath, {
    startedAt,
    wrapperPid,
    startProcessPid: launched.startProcessPid || wrapperPid,
    detached: true,
    launch: 'Start-Process+launcher',
    wrapperPath,
    repoRoot,
    outLog: launched.outLog,
    errLog: launched.errLog,
    pidFile: launched.pidFile || null,
    aliveAtStart: stillAlive,
  });

  const watch = readJson(watchPath) || {};
  watch.h3StartedAt = startedAt;
  watch.h3WrapperPid = wrapperPid;
  watch.h3DetachLog = launched.outLog;
  if (!watch.status || watch.status === 'closed') watch.status = 'watching';
  writeJson(watchPath, watch);

  process.stdout.write(
    JSON.stringify(
      {
        ok: true,
        action: 'started',
        startedAt,
        wrapperPid,
        alive: stillAlive,
        runDir,
        repoRoot,
        outLog: launched.outLog,
        errLog: launched.errLog,
      },
      null,
      2,
    ) + '\n',
  );
  process.exit(stillAlive ? 0 : 1);
}

main();
